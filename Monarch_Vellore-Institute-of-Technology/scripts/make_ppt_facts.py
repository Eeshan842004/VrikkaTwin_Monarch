def R(name: str) -> dict:
    p = REPORTS_DIR / f"{name}.json"
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else {}


def ci(c, d=4, s=1.0) -> str:
    return f"{c[0] * s:.{d}f}-{c[1] * s:.{d}f}" if c else "NOT AVAILABLE"


def pct(x, d=1) -> str:
    return "NOT AVAILABLE" if x is None else f"{100 * x:.{d}f} %"


def test_summary() -> str:
    try:
        out = subprocess.run([sys.executable, "-m", "pytest", "-o", "addopts=", "-p", "no:cacheprovider", "-W",
                              "ignore", "-q", "tests"], cwd=PROJECT_ROOT, capture_output=True, text=True,
                             timeout=1800).stdout
        m = re.findall(r"(\d+ passed[^\n]*)", out)
        return m[-1] if m else "could not parse"
    except subprocess.SubprocessError as e:
        return f"NOT AVAILABLE ({e})"


def ci_status() -> str:
    try:
        import requests
        r = requests.get("https://api.github.com/repos/Eeshan842004/VrikkaTwin_Monarch/actions/runs?per_page=1",
                         timeout=30).json()["workflow_runs"][0]
        return (f"last GitHub Actions run #{r['run_number']} on commit {r['head_sha'][:7]} "
                f"('{r['display_title']}'): {r['conclusion']} (source: api.github.com, workflow .github/workflows/ci.yml)")
    except Exception as e:  # noqa: BLE001
        return f"NOT AVAILABLE ({e})"


def local_ahead() -> str:
    out = subprocess.run(["git", "rev-list", "--count", "origin/main..main"], cwd=ROOT, capture_output=True,
                         text=True).stdout.strip()
    return out or "?"


